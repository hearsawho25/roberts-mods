const BY_THEME: Record<ThemeId, readonly Entry[]> = {
  prompting: PROMPTING,
  files: FILES,
  commands: COMMANDS,
  memory: MEMORY,
  agents: AGENTS,
  build: BUILD,
  habits: HABITS,
}

export const PER_THEME = 52
export const TOTAL = THEMES.length * PER_THEME + 1

const CLOSER: Challenge = {
  id: 'closer',
  theme: 'prompting',
  title: 'Write your next year',
  task: 'Ask Claude to look back at what you have practised this year and help you write five challenges of your own for the year ahead.',
  isCloser: true,
}

function deal(): readonly Challenge[] {
  const list: Challenge[] = []
  for (let round = 0; round < PER_THEME; round++) {
    for (const theme of THEMES) {
      const entry = BY_THEME[theme.id][round]
      if (entry === undefined) continue
      const [title, task] = entry
      const id = `${theme.id}-${String(round + 1).padStart(2, '0')}`
      list.push({ id, theme: theme.id, title, task, isCloser: false })
    }
  }
  list.push(CLOSER)
  return list
}

/** All challenges in the order they are dealt: one of each theme in turn, then the closer. */
export const CHALLENGES: readonly Challenge[] = deal()

export const BY_ID: ReadonlyMap<string, Challenge> = new Map(CHALLENGES.map(one => [one.id, one]))

export function themeOf(challenge: Challenge): Theme {
  return THEMES.find(theme => theme.id === challenge.theme) ?? THEMES[0]!
}
